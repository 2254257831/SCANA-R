"""Frozen-policy ACT stress tests on fresh layouts; no training or model selection."""
from pathlib import Path
import argparse, json, hashlib, sys, time
from concurrent.futures import ProcessPoolExecutor
from datetime import datetime, timezone
from experiment import load_policy, predict
from sim_bridge import sim_env, initial_pose, causal_observation
from common import ROOT, WORK, np, torch

OUT = ROOT / 'artifacts/act_extension_v1'
METHODS = ['Clean repeat', 'Gaussian recovery', 'Frozen context', 'Calibrated recovery']
SEEDS = [7, 11, 23, 31, 47]
LAYOUTS = list(range(94000, 94020))
SCENARIOS = ['nominal', 'replan_1', 'replan_4', 'replan_16', 'pulse_early', 'pulse_late', 'observation_noise']

def digest(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2)+'\n', encoding='utf-8', newline='\n')

def run_one(job):
    task, method, seed, layout, scenario = job
    torch.set_num_threads(1)
    dest = OUT/'rollouts'/task/str(seed)/method/scenario/f'{layout}.npz'
    checkpoint = WORK/'independent_test/policies'/task/str(seed)/(method+'.pt')
    if not dest.exists():
        model, ck = load_policy(checkpoint)
        sim_env.BOX_POSE[0] = initial_pose(task, layout)
        env = sim_env.make_sim_env('sim_'+task)
        obs = env.reset().observation
        replanning = int(scenario.split('_')[-1]) if scenario.startswith('replan_') else 8
        pulse_start = 64 if scenario == 'pulse_early' else 160
        rng = np.random.default_rng(layout+730000)
        pulse = rng.normal(size=(8, 14))
        pulse[:, [6, 13]] = 0
        joints = [i for i in range(14) if i not in [6, 13]]
        pulse *= .08 / np.sqrt(np.mean(pulse[:, joints]**2))
        pulse = np.clip(pulse, -.24, .24)
        # Noise is generated by time, independent of policy and replan count.
        perturb = rng.normal(size=(400, len(causal_observation(obs, 0))))
        perturb[:, :14] *= .01
        perturb[:, 14:-1] *= .005
        perturb[:, [6, 13, -1]] = 0
        actions, states, inputs, rewards = [], [], [], []
        try:
            for t in range(400):
                x = causal_observation(obs, t)
                if scenario == 'observation_noise': x = x + perturb[t].astype(np.float32)
                inputs.append(x)
                if t % replanning == 0:
                    chunk = predict(model, ck, x[None]).reshape(16, 14)
                action = chunk[t % replanning].copy()
                if scenario.startswith('pulse_') and pulse_start <= t < pulse_start+8:
                    action += pulse[t-pulse_start]
                actions.append(action); states.append(obs['qpos'].copy())
                ts = env.step(action); obs = ts.observation; rewards.append(float(ts.reward))
        finally: env.close()
        dest.parent.mkdir(parents=True, exist_ok=True)
        temp = dest.with_suffix('.tmp.npz')
        np.savez_compressed(temp, action=np.asarray(actions), state=np.asarray(states),
                            input=np.asarray(inputs), reward=np.asarray(rewards))
        temp.replace(dest)
    with np.load(dest) as d: r = d['reward']
    end = (64 if scenario == 'pulse_early' else 160)+8
    return dict(task=task, method=method, seed=seed, layout=layout, scenario=scenario,
                success=int(max(r)==4), terminal_success=int(r[-1]==4),
                post_pulse_success=int(max(r[end:])==4) if scenario.startswith('pulse_') else '',
                max_reward=float(max(r)), total_reward=float(sum(r)),
                checkpoint_sha256=digest(checkpoint), rollout_sha256=digest(dest))

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--workers', type=int, default=8); args=ap.parse_args()
    import pandas as pd
    protocol = dict(version=1, tasks=['transfer_cube','insertion'], methods=METHODS,
        training_seeds=SEEDS, layouts=LAYOUTS, scenarios=SCENARIOS, horizon=400,
        purpose='External execution stress tests and receding-horizon action replanning; not high-level language planning.',
        pulse='8 steps; starts at step 64 or 160; joint RMS 0.08 rad, cap 0.24 rad, grippers unchanged; shared across methods and seeds on each layout.',
        observation_noise='Independent Gaussian sigma 0.01 rad for joint input and 0.005 m for object xyz; grippers/clock unchanged; current input only.',
        primary='All records reported. For pulses, post-pulse success is the recovery endpoint. Ever/terminal successes also reported.',
        source_checkpoint='Existing frozen policies; no fitting, selection or fine-tuning on the new layouts.',
        script_sha256=digest(__file__))
    path=OUT/'protocol_frozen.json'
    if path.exists():
        previous=json.loads(path.read_text(encoding='utf-8'))
        assert {k:v for k,v in previous.items() if k!='frozen_utc'} == protocol, 'Protocol changed; use a new version.'
    else:
        protocol['frozen_utc']=datetime.now(timezone.utc).isoformat(); dump(path,protocol)
    jobs=[(t,m,s,l,c) for t in protocol['tasks'] for m in METHODS for s in SEEDS for c in SCENARIOS for l in LAYOUTS]
    rows=[];start=time.monotonic()
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        for row in pool.map(run_one,jobs,chunksize=1):
            rows.append(row)
            if len(rows)%100==0:
                pd.DataFrame(rows).to_csv(OUT/'per_episode.partial.csv',index=False)
                print(f'ACT extension {len(rows)}/{len(jobs)}; elapsed {time.monotonic()-start:.0f}s',flush=True)
    pd.DataFrame(rows).to_csv(OUT/'per_episode.csv',index=False)
    dump(OUT/'completion.json',dict(rollouts=len(rows),seconds=time.monotonic()-start,protocol_sha256=digest(path)))
    print('ACT extension completed.',flush=True)

if __name__=='__main__': main()
